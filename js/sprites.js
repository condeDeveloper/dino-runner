function drawSprite(ctx, rows, x, y, scale, color) {
  ctx.fillStyle = color;
  for (let r = 0; r < rows.length; r++) {
    const row = rows[r];
    for (let c = 0; c < row.length; c++) {
      if (row[c] === '#') ctx.fillRect(Math.round(x + c * scale), Math.round(y + r * scale), scale + 0.5, scale + 0.5);
    }
  }
}
function spriteSize(rows, scale) { return { w: rows[0].length * scale, h: rows.length * scale }; }
